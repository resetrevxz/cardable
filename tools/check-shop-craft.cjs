/* Collection-room UI: real input, pool browsing, motion policy and cleanup. */
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
const url = 'file:///' + path.join(root, 'index.html').replace(/\\/g, '/');
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, executablePath: process.env.SHOP_BROWSER_PATH || undefined });
  const context = await browser.newContext({ viewport: { width: 1366, height: 768 },
    recordVideo: process.env.SHOP_RECORD ? { dir: path.join(root, 'qa-output/shop-craft-video'), size: { width: 1366, height: 768 } } : undefined });
  const page = await context.newPage();
  const errors = [], network = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
  await page.goto(url);
  await page.waitForFunction(() => Cardable.setup && !Cardable.setup.loading);
  await page.evaluate(() => {
    if (Cardable.tutorial.active) Cardable.tutorial.skipButton.click();
    Cardable.settings.applyPreset('high'); Cardable.currency.add(100000, 'dev');
  });
  await page.locator('#shop-entry').click();
  await page.waitForTimeout(1000);
  const before = await page.evaluate(() => ({ currency: Cardable.state.current.currency, inventory: Cardable.state.current.inventory.length,
    serial: Cardable.state.current.serialCounter, shop: Cardable.state.current.shop }));
  const range = page.locator('.shop-turntable-range');
  await range.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await range.inputValue(), '1');
  assert.equal(await page.locator('.shop-pack-exhibit').evaluate(el => el.style.getPropertyValue('--pack-yaw')), '1deg');
  await page.locator('.shop-turntable-reset').click();
  assert.equal(await range.inputValue(), '0');
  await page.screenshot({ path: path.join(root, 'artifacts/shop-craft-desktop.png') });
  await page.locator('.shop-jump').click();
  await page.waitForTimeout(1000);
  const art = page.locator('.shop-offer-art').first();
  await art.hover();
  assert.match(await art.evaluate(el => el.style.getPropertyValue('--light-x')), /%/);
  await page.screenshot({ path: path.join(root, 'artifacts/shop-craft-selection.png') });
  await art.click();
  await page.locator('.shop-turn-card').click();
  await page.waitForTimeout(900);
  assert.equal(await page.locator('.shop-detail-card .collectible-card').getAttribute('data-side'), 'back');
  await page.keyboard.press('r');
  await page.waitForTimeout(900);
  assert.equal(await page.locator('.shop-detail-card .collectible-card').getAttribute('data-side'), 'front');
  await page.locator('.shop-back').click();
  await page.locator('.shop-feature .shop-inspect').click();
  assert.equal(await page.locator('.shop-vault-select option').count(), 17);
  const first = await page.locator('.shop-vault-copy h3').textContent();
  await page.locator('.shop-vault-next').click();
  assert.notEqual(await page.locator('.shop-vault-copy h3').textContent(), first);
  if (process.env.SHOP_RECORD) await page.waitForTimeout(500);
  await page.locator('.shop-vault-select').selectOption('16');
  assert.equal(await page.locator('.shop-vault-count').textContent(), '17 / 17');
  if (process.env.SHOP_RECORD) await page.waitForTimeout(500);
  await page.locator('.shop-vault-next').click();
  assert.equal(await page.locator('.shop-vault-copy h3').textContent(), first);
  const views = await page.evaluate(() => Cardable.cardView.stats.liveViews);
  if (!process.env.SHOP_RECORD) for (let index = 0; index < 25; index++) await page.locator('.shop-vault-next').click();
  assert.equal(await page.evaluate(() => Cardable.cardView.stats.liveViews), views);
  await page.locator('.shop-vault').scrollIntoViewIfNeeded();
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(root, 'artifacts/shop-craft-vault.png') });
  const after = await page.evaluate(() => ({ currency: Cardable.state.current.currency, inventory: Cardable.state.current.inventory.length,
    serial: Cardable.state.current.serialCounter, shop: Cardable.state.current.shop }));
  assert.deepEqual(after, before, 'Exhibit interactions changed gameplay');
  await page.locator('.shop-back').click();
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, get: () => true });
    document.dispatchEvent(new Event('visibilitychange'));
  });
  assert.equal(await page.locator('.shop-screen').getAttribute('data-shop-hidden'), 'true');
  const paused = await page.locator('.shop-pack-exhibit').evaluate(el => el.getAnimations().map(animation => animation.playState));
  assert.ok(paused.length > 0); assert.ok(paused.every(state => state === 'paused'));
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
  await page.evaluate(() => Cardable.settings.set('hoverAnimations', false));
  assert.equal(await page.locator('.shop-screen').getAttribute('data-shop-hover'), 'false');
  await page.evaluate(() => Cardable.settings.set('animationQuality', 'very-low'));
  assert.equal(await page.locator('.shop-screen').getAttribute('data-shop-motion'), 'static');
  await page.evaluate(() => { Cardable.settings.set('motion', 'on'); Cardable.settings.set('rarityColor', 'mono'); });
  assert.equal(await page.locator('.shop-screen').getAttribute('data-shop-motion'), 'static');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(root, 'artifacts/shop-craft-mobile-mono.png') });
  await page.locator('.shop-jump').click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(root, 'artifacts/shop-craft-mobile-selection.png') });
  await page.keyboard.press('Escape');
  const closed = await page.evaluate(() => Cardable.fx.stats.subscribers);
  await page.locator('#shop-entry').click(); await page.locator('.shop-close').click();
  assert.equal(await page.evaluate(() => Cardable.fx.stats.subscribers), closed);
  assert.deepEqual(errors, []); assert.deepEqual(network, []);
  console.log(JSON.stringify({ pass: true, pool: 17, rotateKeyboard: true, cardReverse: true, previewNonSpending: true,
    reducedMotion: true, repeatedCloseStable: true, errors, network }));
  const video = page.video();
  await context.close();
  if (video) await video.saveAs(path.join(root, 'artifacts/shop-craft-tour.webm'));
  await browser.close(); browser = null;
})().catch(async error => { console.error(error); process.exitCode = 1; if (browser) await browser.close(); });

'use strict';
// Isolated file:// browser context; never reads or changes the player's save.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
const output = process.env.CARDABLE_QA_OUTPUT || path.resolve(__dirname, '../../../outputs/activity');
const evidence = { groups: [], errors: [], network: [] };
const url = pathToFileURL(path.resolve(__dirname, '../index.html')).href;
async function main() {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    page.on('pageerror', e => evidence.errors.push(e.stack));
    page.on('request', r => { if (/^https?:/.test(r.url())) evidence.network.push(r.url()); });
    await page.clock.install();
    await page.goto(url);
    await page.evaluate(() => {
      const C = Cardable; C.tutorial.skipButton.click();
      const card = C.data.cards.find(c => !c.retired && c.active !== false);
      C.state.current.inventory.push({ instanceId: 'activity-owned', cardId: card.id, serial: C.serial.format(C.state.current.playerCode, 1), pulledAt: Date.now(), seen: true, variantId: null, cardSkinId: null, packId: 'standard' });
      C.state.current.serialCounter = 1;
      C.state.current.packs.ready = 2; C.state.current.packs.timerStartedAt = Date.now();
      C.state.save();
    });
    await page.clock.runFor(1000);
    await page.mouse.move(600, 300);
    await page.clock.runFor(700);
    const opacity = async selector => { await page.waitForTimeout(700); return page.locator(selector).evaluate(el => Number(getComputedStyle(el).opacity)); };
    // Current resting-menu design keeps the gear visible away from the corner.
    assert.equal(await opacity('.settings-corner'), 1);
    assert((await opacity('.inventory-sheet')) < .4);
    await page.mouse.move(1310, 65); await page.clock.runFor(700);
    assert.equal(await opacity('.settings-corner'), 1);
    await page.mouse.move(683, 755); await page.clock.runFor(700);
    assert.equal(await page.evaluate(() => Cardable.inventory.active), false);
    assert((await page.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    assert((await opacity('.inventory-sheet')) > .8);
    await page.evaluate(() => Cardable.inventory.request(true));
    assert((await page.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    await page.clock.runFor(1000);
    assert.equal(await opacity('.settings-corner'), 0);
    await page.screenshot({ path: path.join(output, 'inventory-ready.png') });
    await page.evaluate(() => Cardable.inventory.request(false)); await page.clock.runFor(1200);
    await page.mouse.move(600, 300); await page.clock.runFor(700);
    assert.equal(await page.evaluate(() => Cardable.inventory.rendered.size), 0);
    const grip = await page.locator('.inventory-grip').boundingBox();
    await page.mouse.move(grip.x + grip.width/2, grip.y + grip.height/2);
    await page.mouse.down(); await page.mouse.move(grip.x + grip.width/2, grip.y - 200, { steps: 6 });
    await page.clock.runFor(100);
    assert((await page.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    assert.equal(await page.locator('.inventory-content').evaluate(el => getComputedStyle(el).visibility), 'visible');
    await page.mouse.up(); await page.clock.runFor(1200);
    await page.evaluate(() => Cardable.inventory.request(false)); await page.clock.runFor(1200);
    await page.mouse.move(600, 300); await page.clock.runFor(700);
    evidence.groups.push('Translucent inventory brightens nearby; bounded thumbnails mount before opening, and are released away; settings hide under inventory.');
    await page.evaluate(() => Cardable.events.emit('menu:activity'));
    await page.clock.fastForward(14900);
    assert.equal(await page.evaluate(() => Cardable.menu.idle), false);
    await page.clock.runFor(800);
    assert.equal(await page.evaluate(() => Cardable.menu.idle), true);
    assert.equal(await opacity('.wordmark'), 1);
    assert.equal(await opacity('.pack-meta'), 1);
    assert.match(await page.locator('.pack-metrics').textContent(), /1 card.*2 \/ 4 packs/);
    assert.equal(await page.locator('.wordmark').evaluate(el => getComputedStyle(el).transform), 'matrix(0.65, 0, 0, 0.65, 0, 0)');
    await page.screenshot({ path: path.join(output, 'idle-15s.png') });
    evidence.groups.push('At 15 seconds the card, timer, stock/refill visualizer, card/pack counts and smaller logo remain visible.');
    await page.clock.fastForward(600000);
    assert.equal(await page.evaluate(() => Cardable.menu.afk), true);
    assert.equal(await page.locator('.pack-unit').first().evaluate(el => getComputedStyle(el).visibility), 'hidden');
    assert.equal(await page.locator('.pack-meta').evaluate(el => getComputedStyle(el).visibility), 'visible');
    const before = await page.evaluate(() => ({ frames: Cardable.fx.stats.frameCount, timer: document.querySelector('.pack-timer').getAttribute('aria-label'), fill: document.querySelectorAll('.stock-card__fill')[2].style.transform, draws: Cardable.dots.stats.draws }));
    await page.clock.runFor(2100);
    const after = await page.evaluate(() => ({ frames: Cardable.fx.stats.frameCount, timer: document.querySelector('.pack-timer').getAttribute('aria-label'), fill: document.querySelectorAll('.stock-card__fill')[2].style.transform, draws: Cardable.dots.stats.draws }));
    assert(after.frames - before.frames <= 4); assert.equal(after.draws, before.draws); assert.notEqual(after.fill, before.fill);
    await page.clock.runFor(61000);
    assert.notEqual(await page.locator('.pack-timer').getAttribute('aria-label'), before.timer);
    evidence.afkFramesIn2Seconds = after.frames - before.frames;
    await page.screenshot({ path: path.join(output, 'afk-10min.png') });
    await page.mouse.move(601, 301); await page.clock.runFor(500);
    assert.equal(await page.evaluate(() => Cardable.menu.afk || Cardable.menu.idle), false);
    assert.equal(await page.locator('.pack-unit').first().evaluate(el => getComputedStyle(el).visibility), 'visible');
    evidence.groups.push('After 10 minutes the card scene sleeps; only metrics update about once a second, and pointer movement restores it.');
    await page.keyboard.press('s'); await page.clock.runFor(700);
    assert.equal(await page.evaluate(() => Cardable.preferences.open), true);
    assert.equal(await opacity('.settings-corner'), 0);
    await page.evaluate(() => Cardable.preferences.close()); await page.clock.runFor(700);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.evaluate(() => Cardable.inventory.request(true)); await page.clock.runFor(500);
    assert((await page.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    await page.evaluate(() => Cardable.inventory.request(false)); await page.clock.runFor(500);
    await page.evaluate(() => Cardable.inventoryModel.update({ viewMode: 'grid' }));
    await page.mouse.move(683, 755); await page.clock.runFor(500);
    assert((await page.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    await page.evaluate(() => Cardable.inventory.request(true));
    assert((await page.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    await page.evaluate(() => Cardable.inventory.request(false)); await page.clock.runFor(500);
    evidence.groups.push('Settings panel suppresses its gear; reduced motion and Grid also render cards immediately.');
    await page.evaluate(() => {
      const C = Cardable, s = C.state.current, card = C.data.cards.find(c => !c.retired && c.active !== false);
      s.serialCounter += 1;
      const packId = C.data.packs.find(p => p.enabled).id;
      s.pendingReveal = { packId, committedAt: Date.now(), keptCount: 0, cards: [{ instanceId: 'activity-pending', cardId: card.id, serial: C.serial.format(s.playerCode, s.serialCounter), pulledAt: Date.now(), seen: false, variantId: null, cardSkinId: null, packId }] };
      C.state.save();
    });
    await page.reload(); await page.clock.runFor(1000);
    assert.equal(await page.evaluate(() => Cardable.opening.phase), 'revealed');
    const snapshot = await page.evaluate(() => JSON.stringify(Cardable.state.current));
    await page.clock.fastForward(601000);
    assert.equal(await page.evaluate(() => Cardable.menu.afk), true);
    assert.equal(await page.locator('.opening-stage').evaluate(el => getComputedStyle(el).visibility), 'hidden');
    assert.equal(await page.evaluate(() => JSON.stringify(Cardable.state.current)), snapshot);
    await page.keyboard.press('Shift'); await page.clock.runFor(500);
    assert.equal(await page.evaluate(() => Cardable.menu.afk), false);
    assert.equal(await page.evaluate(() => Cardable.opening.phase), 'revealed');
    await page.keyboard.press('Space'); await page.clock.runFor(5000);
    assert.equal(await page.evaluate(() => Cardable.state.current.inventory.filter(i => i.instanceId === 'activity-pending').length), 1);
    assert.equal(await page.evaluate(() => Cardable.state.current.pendingReveal), null);
    evidence.groups.push('AFK hides a pending revealed card without altering the save; keyboard wake returns the reveal and Keep collects it exactly once.');
    const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true });
    touch.on('pageerror', e => evidence.errors.push(e.stack));
    touch.on('request', r => { if (/^https?:/.test(r.url())) evidence.network.push(r.url()); });
    await touch.clock.install(); await touch.goto(url);
    await touch.evaluate(() => Cardable.tutorial.skipButton.click()); await touch.clock.runFor(1000);
    await touch.waitForTimeout(700);
    assert.equal(await touch.locator('.settings-corner').evaluate(el => getComputedStyle(el).opacity), '1');
    await touch.locator('.inventory-arrow').tap(); await touch.clock.runFor(1000);
    assert((await touch.evaluate(() => Cardable.inventory.rendered.size)) > 0);
    await touch.waitForTimeout(700);
    assert.equal(await touch.locator('.settings-corner').evaluate(el => getComputedStyle(el).opacity), '0');
    await touch.evaluate(() => Cardable.inventory.request(false)); await touch.clock.runFor(1000);
    await touch.evaluate(() => { Cardable.settings.set('idleFade', 'never'); Cardable.events.emit('menu:activity'); });
    await touch.clock.fastForward(20000);
    assert.equal(await touch.evaluate(() => Cardable.menu.idle), false);
    await touch.clock.fastForward(600000);
    assert.equal(await touch.evaluate(() => Cardable.menu.afk), true);
    await touch.screenshot({ path: path.join(output, 'phone-afk.png') });
    await touch.touchscreen.tap(195, 400); await touch.clock.runFor(500);
    assert.equal(await touch.evaluate(() => Cardable.menu.afk), false);
    evidence.groups.push('Phone touch keeps settings reachable, suppresses it under inventory, renders cards on tap and wakes AFK; Never disables ordinary fading while AFK still sleeps.');
    assert.deepEqual(evidence.errors, []); assert.deepEqual(evidence.network, []);
  } finally {
    fs.writeFileSync(path.join(output, 'evidence.json'), JSON.stringify(evidence, null, 2));
    await browser.close();
  }
  console.log(JSON.stringify(evidence, null, 2));
}
main().catch(e => { console.error(e); process.exitCode = 1; });

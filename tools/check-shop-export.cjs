/* Export a real acquired copy and receipts without adopting a rejected purchase. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');let browser;
const root=path.resolve(__dirname,'..'),qa=path.join(root,'qa-output');
fs.mkdirSync(qa,{recursive:true});const output=fs.mkdtempSync(path.join(qa,'shop-export-'));
assert.ok(output.startsWith(qa+path.sep));
(async()=>{
  browser=await chromium.launch({headless:true,executablePath:process.env.SHOP_BROWSER_PATH||undefined});
  const page=await browser.newPage({viewport:{width:1366,height:768},acceptDownloads:true}),errors=[],network=[];
  page.on('pageerror',error=>errors.push(error.message));page.on('request',request=>{if(/^https?:/.test(request.url()))network.push(request.url());});
  await page.goto('file:///'+path.join(root,'index.html').replace(/\\/g,'/'));
  await page.waitForFunction(()=>Cardable.setup&&!Cardable.setup.loading);
  await page.evaluate(()=>{if(Cardable.tutorial.active)Cardable.tutorial.skipButton.click();Cardable.settings.applyPreset('high');Cardable.settings.set('shopMotion','quiet');Cardable.currency.add(100000,'dev');});
  await page.locator('#shop-entry').click();const buy=page.locator('.shop-offer .shop-hold').first();
  await buy.focus();await page.keyboard.down('Space');await page.waitForTimeout(1650);await page.keyboard.up('Space');
  await page.locator('.shop-receipt').waitFor();await page.locator('.shop-back').click();
  const snapshot=await page.evaluate(()=>JSON.stringify(Cardable.state.current));
  await page.evaluate(()=>{Cardable.state.beforeWrite=()=>{throw Error('Rejected purchase before export');};});
  const rejected=page.locator('.shop-offer .shop-hold').nth(1);
  await rejected.focus();await page.keyboard.down('Space');await page.waitForTimeout(1650);await page.keyboard.up('Space');
  assert.equal(await page.evaluate(()=>Cardable.state.current.inventory.length),1);
  assert.equal(await page.evaluate(()=>Cardable.state.lastWriteSucceeded),false);
  await page.locator('.shop-options-control').click();await page.locator('.shop-save-status-open').click();
  assert.equal(await page.locator('.shop-save-export').isEnabled(),true);
  const downloadEvent=page.waitForEvent('download');await page.locator('.shop-save-export').click();const downloaded=await downloadEvent;
  assert.match(downloaded.suggestedFilename(),/^cardable-save-\d{4}-\d{2}-\d{2}-\d{2}-\d{2}-\d{2}\.json$/);
  const filename=path.join(output,'collection.json');await downloaded.saveAs(filename);
  const text=fs.readFileSync(filename,'utf8'),envelope=JSON.parse(text);
  assert.equal(envelope.app,'cardable');assert.equal(envelope.save.inventory.length,1);assert.equal(envelope.save.shop.receipts.length,1);
  assert.equal(envelope.save.currency,JSON.parse(snapshot).currency);assert.equal(envelope.save.shop.days[0].offers[1].purchased,false);
  const parsed=await page.evaluate(text=>Cardable.saveTools.parse(text),text);assert.equal(parsed.save.inventory.length,1);
  assert.equal(await page.locator('.shop-save-export-note').innerText(),'Download started.');
  assert.equal(await page.evaluate(()=>JSON.stringify(Cardable.state.current)),snapshot,'Export changed collection state');
  assert.equal(await page.evaluate(()=>Cardable.state.lastWriteSucceeded),false,'Export silently retried saving');
  await page.locator('.shop-save-export-note').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'artifacts/shop-export-desktop.png')});
  await page.evaluate(()=>{window.shopDownload=Cardable.saveFiles.download;Cardable.saveFiles.download=()=>{throw Error('Export startup fixture');};});
  await page.locator('.shop-save-export').click();assert.equal(await page.locator('.shop-save-export-note').getAttribute('data-state'),'error');
  assert.match(await page.locator('.shop-save-export-note').innerText(),/Export could not start/);
  await page.evaluate(()=>{Cardable.state.beforeWrite=null;Cardable.state.save();Cardable.settings.set('rarityColor','mono');});
  await page.setViewportSize({width:390,height:844});await page.locator('.shop-save-export-note').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'artifacts/shop-export-mobile-mono.png')});
  assert.ok(await page.locator('.shop-scroll').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  assert.ok(await page.locator('.shop-save-export').evaluate(el=>el.getBoundingClientRect().height>=44));
  await page.evaluate(()=>{Cardable.state.recovery={pending:true,reason:'export-fixture'};window.exportAttempts=0;Cardable.saveFiles.download=()=>exportAttempts++;window.dispatchEvent(new Event('focus'));});
  assert.equal(await page.locator('.shop-save-export').isDisabled(),true);
  await page.locator('.shop-save-export').dispatchEvent('click');assert.equal(await page.evaluate(()=>exportAttempts),0);
  await page.evaluate(()=>{Cardable.state.recovery=null;Cardable.saveFiles.download=shopDownload;Cardable.state.save();});
  // Reimport the actual downloaded envelope through the existing checksum-checked route.
  await page.evaluate(text=>Cardable.saveTools.importText(text),text);
  assert.equal(await page.evaluate(()=>Cardable.state.current.shop.receipts.length),1);
  assert.equal(await page.evaluate(()=>Cardable.state.current.inventory.length),1);
  assert.equal(await page.evaluate(()=>Cardable.state.current.currency),envelope.save.currency);
  assert.equal(await page.locator('.shop-save-details').count(),1);
  await page.locator('.shop-close').click();assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
  console.log(JSON.stringify({pass:true,realDownload:true,validEnvelope:true,rejectedPurchaseExcluded:true,noSaveRetry:true,
    errorFeedback:true,recoveryBlocked:true,importRoundTrip:true,mobileMono:true}));
  await browser.close();browser=null;
})().catch(async error=>{console.error(error);process.exitCode=1;if(browser)await browser.close();});

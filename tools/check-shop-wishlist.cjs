/* Durable wishlist metadata, saved markers/order and read-only save status. */
const assert=require('node:assert/strict'),path=require('node:path');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');let browser;
(async()=>{
  browser=await chromium.launch({headless:true,executablePath:process.env.SHOP_BROWSER_PATH||undefined});
  const page=await browser.newPage({viewport:{width:1366,height:768}}),errors=[],network=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(/^https?:/.test(request.url()))network.push(request.url());});
  await page.goto('file:///'+path.join(root,'index.html').replace(/\\/g,'/'));
  await page.waitForFunction(()=>Cardable.setup&&!Cardable.setup.loading);
  await page.evaluate(()=>{if(Cardable.tutorial.active)Cardable.tutorial.skipButton.click();Cardable.settings.applyPreset('high');Cardable.settings.set('shopMotion','quiet');Cardable.currency.add(100000,'dev');});
  await page.locator('#shop-entry').click();
  const business=()=>page.evaluate(()=>({currency:Cardable.state.current.currency,serial:Cardable.state.current.serialCounter,
    inventory:Cardable.state.current.inventory.length,shop:JSON.parse(Cardable.state.encode(Cardable.state.current.shop)),packs:Cardable.state.current.packs.ready}));
  const before=await business(),targetCard=await page.locator('.shop-offer').nth(3).getAttribute('data-card-id');
  const tile=()=>page.locator('.shop-offer[data-card-id="'+targetCard+'"]');
  await tile().locator('.shop-wishlist-summary').click();
  await tile().locator('.shop-wishlist-new summary').click();
  await tile().locator('.shop-wishlist-name').fill('Collector targets');
  await tile().locator('.shop-wishlist-create').click();
  const wishlist=await page.evaluate(()=>Cardable.inventoryModel.current.collections.find(list=>list.name==='Collector targets'));
  assert.equal(wishlist.kind,'wishlist');assert.deepEqual(wishlist.cardIds,[targetCard]);
  assert.equal(await page.evaluate(()=>Cardable.inventoryModel.current.activeCollectionId),'all');
  assert.equal(await tile().locator('.shop-wishlist-badge').isVisible(),true);
  await tile().locator('.shop-wishlist-priority').selectOption('high');
  assert.equal(await page.evaluate(({id,card})=>Cardable.inventoryModel.current.collections.find(list=>list.id===id).priorities[card],{id:wishlist.id,card:targetCard}),'high');
  assert.deepEqual(await business(),before,'Wishlist altered economy or offers');
  await page.locator('.shop-options-control').click();
  await page.locator('.shop-options [data-setting="shopSort"]').selectOption('wanted-first');
  assert.equal(await page.locator('.shop-offer').first().getAttribute('data-card-id'),targetCard);
  assert.equal(await tile().locator('.shop-wishlist-select').inputValue(),wishlist.id);
  assert.equal(await tile().locator('.shop-wishlist-priority').inputValue(),'high');
  await page.locator('.shop-options-close').click();
  await tile().locator('.shop-wishlist-body').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'artifacts/shop-wishlist-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>Cardable.settings.set('rarityColor','mono'));
  await page.screenshot({path:path.join(root,'artifacts/shop-wishlist-mobile-mono.png')});
  assert.ok(await page.locator('.shop-scroll').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.setViewportSize({width:1366,height:768});
  await page.evaluate(()=>{Cardable.state.beforeWrite=()=>{throw Error('wishlist guard fixture');};});
  await tile().locator('.shop-wishlist-priority').selectOption('low');
  assert.equal(await tile().locator('.shop-wishlist-priority').inputValue(),'high','Rejected priority must restore the saved field value');
  assert.equal(await page.evaluate(({id,card})=>Cardable.inventoryModel.current.collections.find(list=>list.id===id).priorities[card],{id:wishlist.id,card:targetCard}),'high');
  await page.evaluate(()=>{Cardable.state.beforeWrite=null;Cardable.state.save();Cardable.state.beforeWrite=()=>{throw Error('wishlist guard fixture');};});
  await tile().locator('.shop-wishlist-toggle').click();
  assert.match(await tile().locator('.shop-wishlist-note').innerText(),/could not be saved/);
  assert.equal(await page.evaluate(({id,card})=>Cardable.inventoryModel.current.collections.find(list=>list.id===id).cardIds.includes(card),{id:wishlist.id,card:targetCard}),true);
  assert.deepEqual(await business(),before);
  await page.evaluate(()=>{Cardable.state.beforeWrite=null;});
  await page.locator('.shop-save-retry').click();
  await tile().locator('.shop-wishlist-toggle').click();
  assert.equal(await tile().locator('.shop-wishlist-badge').isVisible(),false);
  await tile().locator('.shop-wishlist-toggle').click();
  const purchase=await page.evaluate(cardId=>{
    const C=Cardable,day=C.shopState.ensure().snapshot,offer=day.offers.find(item=>item.cardId===cardId);
    return C.shopPurchase.buyCard({...offer,dayKey:day.dayKey});
  },targetCard);
  assert.equal(purchase.ok,true);
  assert.equal(await tile().locator('.shop-wishlist-badge').isVisible(),true,'Purchase removed a wanted definition');
  await page.reload();await page.waitForFunction(()=>Cardable.setup&&!Cardable.setup.loading);
  await page.locator('#shop-entry').click();
  assert.equal(await page.locator('.shop-offer').first().getAttribute('data-card-id'),targetCard);
  assert.equal(await tile().locator('.shop-wishlist-badge').isVisible(),true);
  await page.locator('.shop-options-control').click();
  await page.locator('.shop-marker-toggle').uncheck();
  assert.equal(await tile().locator('.shop-wishlist-badge').isVisible(),false);
  assert.equal(await page.evaluate(()=>Cardable.inventoryModel.current.collections[0].cardIds.length),1);
  await page.locator('.shop-save-status-open').click();
  const fact=label=>page.locator('.shop-save-facts > div').filter({has:page.locator('dt',{hasText:new RegExp('^'+label+'$')})}).locator('dd');
  const statusBefore=await business();
  assert.equal(await fact('Local save').textContent(),'Saved');
  assert.equal(await fact('Desktop backup').textContent(),'Browser only');
  assert.ok((await fact('Game file').textContent()).endsWith(path.join(root,'index.html').replace(/\\/g,'/')));
  await page.locator('.shop-save-check').click();
  assert.deepEqual(await business(),statusBefore,'Status check changed saved data');
  await page.screenshot({path:path.join(root,'artifacts/shop-save-status-browser.png')});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.locator('.shop-scroll').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.screenshot({path:path.join(root,'artifacts/shop-save-status-mobile.png')});
  await page.reload();await page.waitForFunction(()=>Cardable.setup&&!Cardable.setup.loading);
  assert.equal(await page.evaluate(()=>Cardable.settings.get('shopWishlistMarkers')),false);
  const failedCreate=await page.evaluate(()=>{
    const C=Cardable,before=JSON.stringify(C.inventoryModel.current.collections);
    C.state.beforeWrite=()=>{throw Error('create wishlist fixture');};
    const result=C.inventoryModel.create('Must not survive',{kind:'wishlist',durable:true,activate:false});
    C.state.beforeWrite=null;C.state.save();
    return {result,unchanged:JSON.stringify(C.inventoryModel.current.collections)===before};
  });
  assert.deepEqual(failedCreate,{result:false,unchanged:true});
  assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
  console.log(JSON.stringify({pass:true,durableMembership:true,durableCreate:true,priority:true,sort:true,markersSaved:true,
    purchaseKeepsWishlist:true,readOnlyStatus:true,mobile:true,noEconomyChanges:true}));
  await browser.close();browser=null;
})().catch(async error=>{console.error(error);process.exitCode=1;if(browser)await browser.close();});

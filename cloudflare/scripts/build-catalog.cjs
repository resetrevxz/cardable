'use strict';
// Generates cloudflare/src/catalog.js from the game's own data files, so the server validates an import against
// exactly the cards, rarities, finishes and skins the shipped game has. Run after any catalog change:
//   node cloudflare/scripts/build-catalog.cjs
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..', '..');
const sandbox = { console };
sandbox.window = sandbox;
sandbox.Cardable = { data: {} };
vm.createContext(sandbox);
['src/data/rarities.js', 'src/data/cards.js', 'src/data/variants.js'].forEach((f) => vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), sandbox, { filename: f }));
const C = sandbox.Cardable;
const skins = new Set();
fs.readdirSync(path.join(root, 'src', 'data')).filter((f) => f.endsWith('.js')).forEach((f) => {
  const text = fs.readFileSync(path.join(root, 'src', 'data', f), 'utf8');
  for (const m of text.matchAll(/cardSkinId\s*:\s*'([a-z0-9-]{1,40})'/g)) skins.add(m[1]);
  for (const m of text.matchAll(/cardSkins\s*=\s*\[([^\]]*)\]/g)) for (const id of m[1].matchAll(/id\s*:\s*'([a-z0-9-]{1,40})'/g)) skins.add(id[1]);
});
const catalog = {
  cards: Object.fromEntries(C.data.cards.map((c) => [c.id, c.rarity])),
  rarities: Object.fromEntries(C.data.rarities.map((r) => [r.id, r.tier])),
  variants: C.data.variants.map((v) => v.id),
  skins: Array.from(skins).sort(),
  packs: Array.from(new Set(fs.readFileSync(path.join(root, 'src/data/packs.js'), 'utf8').match(/id\s*:\s*'([a-z0-9-]{2,40})'/g) || [])).map((s) => s.replace(/^id\s*:\s*'|'$/g, '')).sort()
};
const hash = require('crypto').createHash('sha256').update(JSON.stringify(catalog)).digest('hex').slice(0, 16);
const out = '// Generated by cloudflare/scripts/build-catalog.cjs from src/data. Do not edit.\nexport const CATALOG = ' + JSON.stringify(Object.assign({ hash: hash }, catalog)) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'catalog.js'), out);
console.log('catalog ' + hash + ': ' + Object.keys(catalog.cards).length + ' cards, ' + catalog.variants.length + ' finishes, ' + catalog.skins.length + ' skins, ' + catalog.packs.length + ' packs');
